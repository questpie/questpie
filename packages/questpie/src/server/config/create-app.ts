type RuntimeConfigStorageInputGuard<TInput> = TInput extends {
	storage?: infer TStorage;
}
	? TStorage extends StorageConfig | undefined
		? unknown
		: { storage?: never }
	: unknown;

function resolveRealtimeConfig(
	realtime: RealtimeConfigInput | undefined,
): RuntimeConfig["realtime"] {
	if (realtime === true) return {};
	return realtime;
}

