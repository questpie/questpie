// ============================================================================

/**
 * Create a Questpie app from a definition object + runtime config.
 *
 */
async function createAppFromDefinition(
	definition: AppDefinition,
	runtime: RuntimeConfig,
): Promise<Questpie<QuestpieConfig>> {
	// 1. Extract root-level entities into an implicit __user module.
	//    This wraps user-provided collections/globals/etc. into a proper module
	//    so they participate in the same merge pipeline as all other modules.
	//    The __user module is appended last → user entities override module contributions.
	const { modules: defModules, ...rootEntities } = definition;
	const hasRootEntities = Object.keys(rootEntities).some(
		(k) => rootEntities[k] !== undefined,
	);
	// Auto-prepend coreModule so its hooks/jobs are always available.
	// Dedup: if user already listed coreModule, keep theirs (last-write-wins).
	const userModules = defModules ?? [];
	const hasCoreAlready = userModules.some((m) => m.name === coreModule.name);
	const allModules = [
		...(hasCoreAlready ? [] : [coreModule as unknown as ModuleDefinition]),
		...userModules,
		...(hasRootEntities
			? [{ name: "__user", ...rootEntities } as ModuleDefinition]
			: []),
	];

	// 2. Resolve modules depth-first
	const flatModules = resolveModules(allModules);

	// 3. Merge all module contributions (including __user)
	let merged = emptyMergedState();
	for (const mod of flatModules) {
		merged = mergeModuleIntoState(merged, mod);
	}

	// 4. Convert messages to translations config
	const mergedTranslations = mergeMessagesIntoConfig(
		merged.translations,
		merged.messages,
	);
	const finalTranslations = runtime.translations
		? mergeTranslationsConfig(mergedTranslations, runtime.translations)
		: mergedTranslations;

	// 5. Build QuestpieConfig — extract consumed config keys
	const allJobs = merged.jobs;
	const hasJobs = Object.keys(allJobs).length > 0;

	// Extract config bucket values
	const cfg = merged.config ?? {};
	const appCfg = cfg.app ?? {};
	const authCfg = cfg.auth ?? {};

	const cmsConfig: QuestpieConfig = {
		app: runtime.app,
		db: runtime.db,
		secret: runtime.secret,
		collections: merged.collections,
		channels: merged.channels,
		globals: merged.globals,
		locale: appCfg.locale,
		auth: authCfg,
		storage: runtime.storage,
		// Read off `merged`, not `definition`. A module that ships an emails/
		// directory contributes its templates through the merge like everything
		// else, and reading the root definition skipped every one of them. The
		// app's own emails/ still arrives, because root entities ride in __user.
		email: merged.emailTemplates
			? { ...(runtime.email ?? {}), templates: merged.emailTemplates }
			: runtime.email,
		queue:
			hasJobs && runtime.queue
				? {
						jobs: allJobs,
						adapter: runtime.queue.adapter,
					}
				: undefined,
		routes: Object.keys(merged.routes).length > 0 ? merged.routes : undefined,
		search: runtime.search,
		realtime: runtime.realtime,
		crdt: runtime.crdt,
		logger: runtime.logger,
		kv: runtime.kv,
		// Was missing until 2026-07-29, which meant `runtimeConfig({
		// observability: { adapter } })` was accepted by the types, silently
		// dropped here, and the service came up disabled — so the documented way
		// to turn tracing on did nothing at all.
		observability: runtime.observability,
		executor: runtime.executor,
		migrations: {
			migrations: [...merged.migrations],
		},
		seeds: {
			seeds: [...merged.seeds],
		},
		autoMigrate: runtime.autoMigrate,
		autoSeed: runtime.autoSeed,
		translations: finalTranslations,
		globalHooks: appCfg.hooks,
		defaultAccess: appCfg.access,
		services:
			Object.keys(merged.services).length > 0 ? merged.services : undefined,
	};

	// 6. Create Questpie instance
	const instance = new Questpie(cmsConfig);

	// 6b. Validated env (from env.ts) — typed via the generated app type.
	if (merged.env && typeof merged.env === "object") {
		instance.env = merged.env as Readonly<Record<string, unknown>>;
	}

	// 7. Store extension state + config bucket on instance.state
	const runtimeExtensions = extractRuntimeExtensions(
		runtime as Record<string, unknown>,
	);
	const extensionState = buildExtensionState(merged, runtimeExtensions);

	// The entire merged config bucket goes to instance.state.config — no filtering.
	// Runtime already extracted what it needs (locale, hooks, auth, etc.) into cmsConfig.
	// state.config is the single source of truth for all plugin configs at runtime.
	if (Object.keys(cfg).length > 0) {
		extensionState.config = cfg;
	}

	instance.state = extensionState;
	instance.crdtManifests = createCrdtRuntimeManifests({
		registry: instance.crdtRegistry,
		config: runtime.crdt,
		artifact: merged.crdtManifest,
		allowMissingForGeneration:
			process.env.QUESTPIE_CRDT_MANIFEST_GENERATION === "1",
	});

	await instance._initServices();

	return instance;
}
