const EXPECTED_OPCODES = [
	0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x81, 0x82, 0x83, 0x84, 0x85,
	0x86, 0x86, 0x86, 0x87, 0x88, 0x89, 0x8a, 0x8b,
];

function bytes(hex: string): Uint8Array {
	return Uint8Array.fromHex(hex);
}

function hex(value: Uint8Array): string {
	return value.toHex();
}

describe("QPCR v1 normative golden vectors", () => {
	it("decodes and byte-for-byte re-encodes all 21 vectors", () => {
		const decoded: CrdtFrameV1[] = [];
		for (const vector of Object.values(GOLDEN)) {
			const frame = decodeCrdtFrameV1(bytes(vector));
			expect(hex(encodeCrdtFrameV1(frame))).toBe(vector);
			decoded.push(frame);
		}
		expect(decoded.map((frame) => frame.opcode)).toEqual(EXPECTED_OPCODES);
	});

	it("preserves the fixed network-order header", () => {
		const frame = decodeCrdtFrameV1(bytes(GOLDEN.updateClient));
		expect(frame).toMatchObject({
			major: 1,
			minor: 0,
			opcode: 0x04,
			connectionSeq: 1n,
			requestId: 1n,
		});
		expect(frame.payload).toMatchObject({
			aggregateEpoch: 3n,
			schemaVersion: 9,
			parts: [
				{
					fieldSlot: 1,
					fieldEpoch: 1n,
					formatVersion: 1,
					baseFieldCursor: 5n,
				},
				{
					fieldSlot: 2,
					fieldEpoch: 2n,
					formatVersion: 1,
					baseFieldCursor: 7n,
				},
			],
		});
	});

	it("decodes grant, revoke, and reset transitions exactly", () => {
		const transitions = [
			decodeCrdtFrameV1(bytes(GOLDEN.fieldGrant)),
			decodeCrdtFrameV1(bytes(GOLDEN.fieldRevoke)),
			decodeCrdtFrameV1(bytes(GOLDEN.fieldReset)),
		].map((frame) => {
			if (frame.opcode !== 0x86) throw new Error("expected FIELD_STATE");
			return frame.payload.transitions[0];
		});

		expect(transitions).toEqual([
			{
				fieldSlot: 1,
				action: 0,
				grant: 0,
				fieldEpoch: 1n,
				headFieldCursor: 0n,
			},
			{
				fieldSlot: 1,
				action: 1,
				grant: 0,
				fieldEpoch: 0n,
				headFieldCursor: 0n,
			},
			{
				fieldSlot: 2,
				action: 2,
				grant: 0,
				fieldEpoch: 2n,
				headFieldCursor: 8n,
			},
		]);
	});
});

