import { describe, expect, test } from "bun:test";
import { existsSync } from "node:fs";
import path from "node:path";

import adminPackageJson from "../packages/admin/package.json";
import crdtYjsPackageJson from "../packages/crdt-yjs/package.json";
import elysiaPackageJson from "../packages/elysia/package.json";
import honoPackageJson from "../packages/hono/package.json";
import mcpPackageJson from "../packages/mcp/package.json";
import nextPackageJson from "../packages/next/package.json";
import openApiPackageJson from "../packages/openapi/package.json";
import questpiePackageJson from "../packages/questpie/package.json";
import sandboxPackageJson from "../packages/sandbox/package.json";
import tanstackDbPackageJson from "../packages/tanstack-db/package.json";
import tanstackQueryPackageJson from "../packages/tanstack-query/package.json";
import workflowsPackageJson from "../packages/workflows/package.json";

/**
 * These maps are generated by tsdown from each package's `exports` config, so a
 * regression here comes from a build config change, not a hand edit.
 */
interface Manifest {
	name: string;
	exports?: Record<string, unknown>;
	publishConfig?: { exports?: Record<string, unknown> };
}

const manifests: Manifest[] = [
	adminPackageJson,
	crdtYjsPackageJson,
	elysiaPackageJson,
	honoPackageJson,
	mcpPackageJson,
	nextPackageJson,
	openApiPackageJson,
	questpiePackageJson,
	sandboxPackageJson,
	tanstackDbPackageJson,
	tanstackQueryPackageJson,
	workflowsPackageJson,
];

const bothMaps = (manifest: Manifest) => [
	["exports", manifest.exports ?? {}] as const,
	["publishConfig.exports", manifest.publishConfig?.exports ?? {}] as const,
];

describe("package export maps", () => {
	// A "./*" entry makes every file in the tarball a public entry point,
	// including generated module internals. Once someone imports one it is
	// public forever, and a wildcard resolve cannot be deprecated with a warning.
	test.each(manifests)("$name declares no wildcard subpath", (manifest) => {
		for (const [label, map] of bothMaps(manifest)) {
			const wildcards = Object.keys(map).filter((key) => key.includes("*"));
			expect(wildcards, `${manifest.name} ${label}`).toEqual([]);
		}
	});

	// questpie/internal/* exists so that a declaration file in a downstream
	// package can name a module the public entry points do not re-export.
	// Declaring only the `types` condition keeps runtime imports out: Node has
	// no condition to match and refuses the specifier.
	describe("questpie internal type subpaths", () => {
		const internalKeys = Object.keys(questpiePackageJson.exports).filter(
			(key) => key.startsWith("./internal/"),
		);

		test("are declared", () => {
			expect(internalKeys.length).toBeGreaterThan(0);
		});

		test.each(internalKeys)("%s is types-only in both maps", (key) => {
			for (const [label, map] of bothMaps(questpiePackageJson)) {
				const conditions = Object.keys(
					(map[key] ?? {}) as Record<string, string>,
				);
				expect(conditions, `${label} ${key}`).toEqual(["types"]);
			}
		});

		test.each(internalKeys)("%s points at a source file that exists", (key) => {
			const entry = (questpiePackageJson.exports as Record<string, unknown>)[
				key
			] as { types: string };
			const source = path.join(
				import.meta.dirname,
				"../packages/questpie",
				entry.types,
			);
			expect(existsSync(source)).toBe(true);
		});
	});
});
